export function Sidebar() {
  const pathname = usePathname();
  const { me } = useAuth();
  return (
    <aside className="fixed inset-y-0 left-0 z-30 hidden w-64 flex-col border-r border-slate-200 bg-white px-4 py-5 dark:border-slate-800 dark:bg-slate-900 lg:flex">
      <div className="px-2"><Logo /></div>
      <nav className="mt-8 flex flex-1 flex-col gap-1">
        {NAV.map((item) => {
          const active = pathname.startsWith(item.href);
          return (
            <Link key={item.href} href={item.href}
              className={`flex items-center gap-3 rounded-xl px-3 py-2.5 text-sm font-medium transition ${
                active
                  ? "bg-brand-50 text-brand-700 dark:bg-brand-900/30 dark:text-brand-300"
                  : "text-slate-600 hover:bg-slate-100 dark:text-slate-400 dark:hover:bg-slate-800 dark:hover:text-slate-200"}`}>
              <Icon path={item.icon} />
              {item.label}
            </Link>
          );
        })}
      </nav>
      {me && (
        <div className="rounded-xl bg-slate-50 p-3 dark:bg-slate-800/60">
          <div className="truncate text-sm font-semibold text-slate-700 dark:text-slate-200">
            {me.full_name || me.email}
          </div>
          <div className="truncate text-xs text-slate-400">{me.email}</div>
        </div>
      )}
    </aside>
  );
}

